"""The dashboard's build-time case maps must match the datasets.

``dashboard/frontend/src/casePrompts.json`` and ``caseTypes.json`` are generated by
``scripts/sync_case_prompts.py`` and imported by the frontend at build time. They
exist so a case row can show its question and its dataset layer even for runs saved
before those fields were persisted.

Nothing forces the script to be re-run after a dataset edit, and the failure is
silent in both directions: a new case shows a blank question, and a case whose layer
changed keeps the old label. That is not hypothetical — merging the chat-scoped Layer
3 cases into the consult layer is exactly the edit that made an id-prefix guess wrong
for eight cases. So the maps are checked here rather than trusted.
"""

from __future__ import annotations

import json
from pathlib import Path

from bench.dataset import case_prompt_map, load_all_cases

SRC = Path(__file__).resolve().parent.parent / "dashboard" / "frontend" / "src"
SYNC_HINT = "run `make case-prompts` (scripts/sync_case_prompts.py) after editing a dataset"


def test_case_prompts_json_matches_the_datasets():
    on_disk = json.loads((SRC / "casePrompts.json").read_text())
    expected = case_prompt_map()

    assert set(on_disk) == set(expected), SYNC_HINT
    differing = {k for k in expected if on_disk[k] != expected[k]}
    assert not differing, f"prompt text drifted for {sorted(differing)} — {SYNC_HINT}"


def test_case_types_json_matches_the_datasets():
    on_disk = json.loads((SRC / "caseTypes.json").read_text())
    expected = {case.id: case.type for case in load_all_cases()}

    assert set(on_disk) == set(expected), SYNC_HINT
    differing = {k for k in expected if on_disk[k] != expected[k]}
    assert not differing, f"layer drifted for {sorted(differing)} — {SYNC_HINT}"


def test_chat_scoped_layer3_cases_are_not_labelled_agent():
    """The specific mislabel the layer map exists to prevent."""
    on_disk = json.loads((SRC / "caseTypes.json").read_text())
    merged = [
        cid for cid in on_disk if cid.startswith("agent_condor_")
    ]
    assert merged, "expected the merged chat-scoped cases to still be in the library"
    assert all(on_disk[cid] == "consult" for cid in merged), {
        cid: on_disk[cid] for cid in merged
    }


# ── The run form's filter options ─────────────────────────────────────────────
def test_combos_reproduce_filter_cases_exactly():
    """`/api/datasets` combos must agree with the filter the runner applies.

    The run form offers three filters that AND together, and the axes barely
    overlap: a Tool case's domain is always a `tool:` bucket and its category is
    always "tool". Offering the routing domains beside a Tools selection let
    "Tools + general_consult" be submitted, and the only feedback was the run being
    refused server-side with "No cases matched the selected filters." The form now
    derives its options and its count from these combinations, so they have to mean
    the same thing as `filter_cases` or the form lies in a new way.
    """
    import itertools

    from bench.dataset import filter_cases

    cases = load_all_cases()
    combos: dict[tuple[str, str, str, str], int] = {}
    for case in cases:
        key = (
            str(case.type),
            str(case.domain),
            str(case.category or ""),
            str(case.risk_level),
        )
        combos[key] = combos.get(key, 0) + 1

    def offered(layers, domain, category, risks):
        return sum(
            n
            for (layer, dom, cat, risk), n in combos.items()
            if (not layers or layer in layers)
            and (not domain or dom == domain)
            and (not category or cat == category)
            and (not risks or risk in risks)
        )

    layer_sets = [[], ["consult"], ["tick"], ["tool"], ["agent"], ["tool", "agent"]]
    domains = [""] + sorted({c.domain for c in cases})
    categories = [""] + sorted({c.category for c in cases if c.category})
    # Risk is a set, not a ceiling, so the mixed selections have to be covered too —
    # "read_only + destructive" is a combination no max-risk parameter could express.
    risk_sets = [
        [],
        ["read_only"],
        ["mutating"],
        ["destructive"],
        ["read_only", "destructive"],
        ["mutating", "destructive"],
    ]

    for layers, domain, category, risks in itertools.product(
        layer_sets, domains, categories, risk_sets
    ):
        assert offered(layers, domain, category, risks) == len(
            filter_cases(
                cases,
                domain=domain or None,
                category=category or None,
                layers=layers or None,
                risk_levels=risks or None,
            )
        ), (
            f"layers={layers} domain={domain!r} category={category!r} risks={risks}"
        )


def test_no_layer_shares_a_domain_with_the_tool_buckets():
    """The specific impossibility the form used to offer."""
    cases = load_all_cases()
    tool_domains = {c.domain for c in cases if c.type == "tool"}
    other_domains = {c.domain for c in cases if c.type != "tool"}
    assert not (tool_domains & other_domains)
    assert all(d.startswith("tool:") for d in tool_domains)
